def varlen(n):
    out = [n & 0x7F]
    n >>= 7
    while n:
        out.insert(0, (n & 0x7F) | 0x80)
        n >>= 7
    return bytes(out)


def track(events, running=False):
    """events: (delta ticks, bytes). running=True drops repeated status bytes."""
    data = bytearray()
    status = None
    for delta, event in events:
        event = bytes(event)
        if running and event[0] < 0xF0 and event[0] == status:
            event = event[1:]
        elif event[0] < 0xF0:
            status = event[0]
        data += varlen(delta) + event
    data += varlen(0) + bytes((0xFF, 0x2F, 0))
    return b'MTrk' + struct.pack('>I', len(data)) + bytes(data)


def midi(tracks, division=480, fmt=None):
    fmt = (0 if len(tracks) == 1 else 1) if fmt is None else fmt
    return b'MThd' + struct.pack('>IHHH', 6, fmt, len(tracks), division) + b''.join(tracks)


def tempo(bpm):
    return (0xFF, 0x51, 3, *int(60_000_000 / bpm).to_bytes(3, 'big'))


def scale(channel=0, notes=(60, 62, 64, 65), length=240):
    events = []
    for n in notes:
        events += [(0, (0x90 | channel, n, 100)), (length, (0x80 | channel, n, 0))]
    return events


class ConverterTests(unittest.TestCase):
    def test_tempo_map_and_quantization(self):
        # 120 BPM: an eighth (240 of 480) is 0.25 s; then 60 BPM doubles it.
        events = [(0, tempo(120))] + scale(notes=(60, 62)) + [(0, tempo(60))] + scale(notes=(64, 65))
        out, report = music.convert_song(midi([track(events)]))
        ons = [(t, a) for t, kind, ch, a, b in out if kind == music.NOTE_ON]
        self.assertEqual(ons, [(0, 60), (25, 62), (50, 64), (100, 65)])
        self.assertEqual(report['seconds'], 1.5)

    def test_running_status_and_format_one_tracks_merge(self):
        a = track([(0, tempo(120))] + scale(notes=(60, 64)), running=True)
        b = track(scale(channel=1, notes=(48, 52)), running=True)
        out, report = music.convert_song(midi([a, b]))
        self.assertEqual(report['notes'], 4)
        self.assertEqual(report['max_polyphony'], 2)
        ons = sorted(a for t, kind, ch, a, b in out if kind == music.NOTE_ON)
        self.assertEqual(ons, [48, 52, 60, 64])

    def test_sustain_pedal_holds_releases(self):
        events = [(0, (0xB0, 64, 127))] + scale(notes=(60, 64, 67)) + [(240, (0xB0, 64, 0))]
        out, report = music.convert_song(midi([track(events)]))
        offs = [t for t, kind, *_ in out if kind == music.NOTE_OFF]
        self.assertEqual(offs, [100, 100, 100])     # All at pedal release, 1.0 s
        self.assertEqual(report['max_polyphony'], 3)

    def test_steals_oldest_when_more_than_nine(self):
        events = [(0, (0x90, 48 + i, 90)) for i in range(11)] + [(480, (0x80, 48 + i, 0)) for i in range(11)]
        out, report = music.convert_song(midi([track(events)]))
        self.assertEqual(report['steals'], 2)
        self.assertEqual(report['max_polyphony'], 9)
        ons = [(ch, a) for t, kind, ch, a, b in out if kind == music.NOTE_ON]
        self.assertEqual(ons[9][0], ons[0][0])      # Note 10 takes over note 1's channel
        self.assertEqual(ons[10][0], ons[1][0])

    def test_drums_dropped_range_folded_and_counted(self):
        events = [(0, (0x99, 36, 100)), (10, (0x89, 36, 0)), (0, (0x90, 5, 100)), (10, (0x80, 5, 0)),
                  (0, (0x90, 120, 100)), (10, (0x80, 120, 0)), (0, (0xE0, 0, 0x50))]
        out, report = music.convert_song(midi([track(events)]))
        self.assertEqual((report['drum_notes'], report['octave_moves'], report['pitch_bends']), (1, 2, 1))
        self.assertEqual(sorted(a for t, kind, ch, a, b in out if kind == music.NOTE_ON), [17, 108 - 12])

    def test_programs_pick_patches_and_volume_attenuates(self):
        events = [(0, (0xC0, 4)), (0, (0xC1, 48)), (0, (0xB1, 7, 64))] + scale(notes=(60,)) + scale(1, (48,))
        out, report = music.convert_song(midi([track(events)]))
        patches = {ch: a for t, kind, ch, a, b in out if kind == music.PATCH}
        self.assertEqual(sorted(patches.values()), [music.PATCH_INDEX['epiano'], music.PATCH_INDEX['pad']])
        levels = [b for t, kind, ch, a, b in out if kind == music.NOTE_ON]
        self.assertEqual(levels[0], music.attenuation(100, 100, 127))
        self.assertGreater(levels[1], levels[0])    # Channel volume 64 is quieter
        self.assertEqual(music.attenuation(0, 100, 127), 63)

    def test_long_rests_use_wait_events_and_pack_layout(self):
        # A 12-minute rest overflows the 16-bit delta.
        events = [(0, tempo(60))] + scale(notes=(60,), length=480) + [(480 * 720, (0x90, 62, 90)),
                                                                    (480, (0x80, 62, 0))]
        song = midi([track(events)])
        pack, reports = music.build_pack([('rest', song), ('scale', midi([track(scale())]))], include_builtin=False)
        magic, version, flags, songs, patches, payload, total = struct.unpack_from('<8s6I', pack)
        self.assertEqual((magic, version, flags, songs, patches), (music.MAGIC, 1, 0, 2, len(music.PATCHES)))
        self.assertEqual((payload, total), (len(pack) - 32, music.checksum(pack[32:])))
        directory = 32 + patches * 12
        name, offset, count, length = struct.unpack_from('<20sIII', pack, directory)
        self.assertEqual(name.rstrip(b'\0'), b'rest')
        events_base = directory + songs * 32
        kinds = [pack[events_base + offset + i * 5 + 2] >> 4 for i in range(count)]
        self.assertIn(music.WAIT, kinds)
        deltas = sum(struct.unpack_from('<H', pack, events_base + offset + i * 5)[0] for i in range(count))
        self.assertEqual(deltas, length)
        self.assertEqual(length, 100 + 72000 + 100)

    def test_rejects_unsupported_files(self):
        with self.assertRaises(ValueError):
            music.convert_song(b'RIFF')
        with self.assertRaises(ValueError):
            music.convert_song(midi([track(scale())], fmt=2))

    def test_folder_build_writes_pack_and_report(self):
        with tempfile.TemporaryDirectory() as folder:
            folder = Path(folder)
            self.assertIsNone(music.build(folder / 'MUSIC.PAK', folder))
            (folder / 'b-second.mid').write_bytes(midi([track(scale())]))
            (folder / 'a-first.MID').write_bytes(midi([track(scale(notes=(67,)))]))
            report = music.build(folder / 'out/MUSIC.PAK', folder)
            self.assertEqual([s['name'] for s in report['songs']], ['a-first', 'b-second'])
            self.assertTrue((folder / 'out/MUSIC.json').is_file())


@unittest.skipUnless(ZIG.is_file() and STAGE.is_dir(), 'native Zig and staged game headers required')
class SequencerTests(unittest.TestCase):
    def test_dos_sequencer_replays_pack(self):
        # Song 0: C4 for 0.5 s, then an E4+G4 chord on a pad for 0.25 s.
        notes = [(0, (0x90, 60, 127)), (240, (0x80, 60, 0)), (0, (0xC0, 48)),
                 (0, (0x90, 64, 127)), (0, (0x90, 67, 127)), (120, (0x80, 64, 0)), (0, (0x80, 67, 0))]
        song = midi([track([(0, tempo(60))] + notes)])
        with tempfile.TemporaryDirectory(prefix='dos-music-pack-') as folder:
            p = Path(folder)
            pack, _ = music.build_pack([('test', song)], include_builtin=False)
            (p / 'MUSIC.PAK').write_bytes(pack)
            bad = bytearray(pack)
            bad[-1] ^= 1
            (p / 'BAD.PAK').write_bytes(bad)
            (p / 'pc.h').write_text('unsigned char inportb(unsigned short);\nvoid outportb(unsigned short,unsigned char);\n')
            exe = p / 'test.exe'
            dos = ROOT / 'src/platform/dos'
            r = subprocess.run([str(x) for x in (ZIG, 'cc', '-target', 'x86-windows-gnu', '-std=gnu99', '-O2',
                                '-fno-builtin', '-Wall', '-Wextra', '-Werror', '-DOPL_PACK_TEST', '-I', p,
                                '-I', dos, '-I', STAGE, ROOT / 'tests/opl_music_native.c', '-o', exe)],
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            r = subprocess.run([str(exe), str(p / 'MUSIC.PAK'), str(p / 'BAD.PAK')], capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn('PASS: pack', r.stdout)


