"""N64 source adaptations shared by stage_core.py and stage_doscraft.py.

Each is an exact, fail-closed replacement that returns a recipe entry, like
DOScraft's overlays. Only x86-specific code is replaced; behavior is kept.
"""
import hashlib

# Towns fmath.h: the three 64-bit-intermediate helpers are x86 inline
# assembly (imull/shrdl/idivl). The C versions give the same results for
# shifts 1..31 (the game's range): low 32 bits of the shifted 64-bit product,
# and quotients truncated toward zero, as idivl does. The x86 versions fault
# on a quotient overflow; callers guarantee there is none.
FMATH_ASM_START = '/* (a*b)>>s with a 64-bit intermediate */\n'
FMATH_ASM_END = '\n#endif\n'
FMATH_C = '''/* (a*b)>>s with a 64-bit intermediate.  N64: C in place of x86 imull/shrdl. */
static inline int mulshift(int a,int b,int s)
{
	return (int)(u32)((long long)a*b>>s);
}
/* (a<<s)/b with a 64-bit intermediate.  Caller guarantees no overflow. */
static inline int divshift(int a,int b,int s)
{
	return (int)(((long long)a<<s)/b);
}

/* (a*b)/c with a 64-bit intermediate */
static inline int muldiv(int a,int b,int c)
{
	return (int)((long long)a*b/c);
}
'''


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def fmath_portable(text):
    """Replace the x86 fixed-point helpers in fmath.h with portable C."""
    if text.count(FMATH_ASM_START) != 1 or text.count(FMATH_ASM_END) != 1:
        raise ValueError('fmath.h helper markers changed')
    start, end = text.index(FMATH_ASM_START), text.index(FMATH_ASM_END)
    removed = text[start:end]
    if '__asm__' not in removed:
        raise ValueError('fmath.h helpers are no longer assembly')
    step = dict(operation='replace', file='fmath.h', before_sha256=sha256(removed.encode()),
                before_bytes=len(removed.encode()), after=FMATH_C)
    return text[:start] + FMATH_C + text[end:], step


def libc_portable(path):
    """Remove DOScraft-staged libc.c's x86 string functions (newlib has them)."""
    text = path.read_text(encoding='utf-8')
    start = 'void *memset(void *d,int c,size_t n)\n'
    end = 'char *itoa_dec(int v,char *buf)\n'
    if text.count(start) != 1 or text.count(end) != 1 or text.index(start) > text.index(end):
        raise ValueError('libc.c span markers changed')
    removed = text[text.index(start):text.index(end)]
    path.write_text(text.replace(removed, ''), encoding='utf-8')
    return dict(operation='remove', file='libc.c', removed_sha256=sha256(removed.encode()),
                removed_bytes=len(removed.encode()))


def adapt_staged(src):
    """Apply every N64 adaptation to a DOScraft-staged src/ directory."""
    steps = [libc_portable(src / 'libc.c')]
    fmath = src / 'fmath.h'
    text, step = fmath_portable(fmath.read_text(encoding='utf-8'))
    fmath.write_text(text, encoding='utf-8')
    steps.append(step)
    return steps


# The 1024-world medium is baked little-endian on the PC. Its header, column
# index, lighting index and V1 checksum tables are read as native u32, which
# the big-endian VR4300 would see byte-swapped. Decision 2026-10-15: keep the
# bake byte-identical to DOScraft's and read those tables little-endian.
# Checksums are byte-wise FNV over the raw bytes and stay before conversion;
# column and lighting payloads are byte streams and need nothing.
N64_LE_H = '''/* Generated by tools/n64_adapt.py: little-endian reads of the PC-baked
   1024-world medium on the big-endian N64. */
#ifndef TOWNSCRAFT64_N64_LE_H
#define TOWNSCRAFT64_N64_LE_H
static inline u32 n64_le32(const u8 *p)
{
	return (u32)p[0]|(u32)p[1]<<8|(u32)p[2]<<16|(u32)p[3]<<24;
}
/* Convert n words in place from little-endian file order. */
static inline void n64_le32_words(u32 *w,u32 n)
{
	for(u32 i=0; i<n; ++i) w[i]=n64_le32((const u8 *)&w[i]);
}
#endif
'''
INDEX_ENTRY = 'const u32 *entry=(const u32 *)columnScratch+{base}*3;'
INDEX_ENTRY_LE = ('u32 entry[3]={{n64_le32(columnScratch+{base}*12),n64_le32(columnScratch+{base}*12+4),'
                  'n64_le32(columnScratch+{base}*12+8)}};')


def _replace(text, before, after, recipe, name):
    if text.count(before) != 1:
        raise ValueError(f'{name}: expected one {before[:50]!r}, found {text.count(before)}')
    recipe.append(dict(operation='replace', file=name, before=before, after=after))
    return text.replace(before, after)


def medium_le32(src, platform):
    """Little-endian medium reads in staged column_hdd.inc and stream_light_cache.inc.

    src is a staged DOScraft src/ directory; the adapted stream_light_cache.inc
    is written there, so world.c's #include finds it before the platform copy.
    """
    recipe = []
    (src / 'n64_le.h').write_text(N64_LE_H, encoding='ascii')
    path = src / 'column_hdd.inc'
    text = path.read_text(encoding='utf-8')
    text = _replace(text, 'static int terrain_init(void)\n',
                    '#include "n64_le.h"\nstatic int terrain_init(void)\n', recipe, path.name)
    text = _replace(text, '\t\tmemcpy(headerCopy,columnScratch,512);\n',
                    '\t\tmemcpy(headerCopy,columnScratch,512);\n\t\tn64_le32_words(headerCopy,128);\n',
                    recipe, path.name)
    text = _replace(text, INDEX_ENTRY.format(base='e'), INDEX_ENTRY_LE.format(base='e'), recipe, path.name)
    text = _replace(text,
                    '\t\t\tif(column_checksum((u8 *)terrainBaseSum,sizeof(terrainBaseSum))!=indexSum)\n'
                    '\t\t\t\tfatal("Corrupt 1024-world index");\n',
                    '\t\t\tif(column_checksum((u8 *)terrainBaseSum,sizeof(terrainBaseSum))!=indexSum)\n'
                    '\t\t\t\tfatal("Corrupt 1024-world index");\n'
                    '\t\t\tn64_le32_words(terrainBaseSum,sizeof(terrainBaseSum)/4);\n', recipe, path.name)
    for word in (4, 5, 6):
        text = _replace(text, f'((u32 *)columnScratch)[{word}]', f'n64_le32(columnScratch+{word * 4})',
                        recipe, path.name)
    path.write_text(text, encoding='utf-8')

    target = src / 'stream_light_cache.inc'
    text = (platform / 'stream_light_cache.inc').read_text(encoding='utf-8')
    text = _replace(text, INDEX_ENTRY.format(base='e'), INDEX_ENTRY_LE.format(base='e'), recipe, target.name)
    text = _replace(text,
                    '    if(column_checksum((u8 *)streamLightSum,sizeof(streamLightSum))!=indexSum)\n'
                    '        fatal("Corrupt prebaked lighting index");\n',
                    '    if(column_checksum((u8 *)streamLightSum,sizeof(streamLightSum))!=indexSum)\n'
                    '        fatal("Corrupt prebaked lighting index");\n'
                    '    n64_le32_words(streamLightSum,sizeof(streamLightSum)/4);\n', recipe, target.name)
    target.write_text(text, encoding='utf-8')
    return recipe
