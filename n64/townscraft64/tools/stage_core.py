"""Stage the Towns core for the N64 into build/core.

Input is the immutable Towns snapshot inside the DOScraft import
(vendor/doscraft/vendor/towns), checked against its MANIFEST.json. Output is
build/core/src (adapted sources), build/core/src/tables.c (generated) and
build/core/stage.json (every replacement applied, with hashes). The pinned
Towns host tests (vendor/towns-tests) are copied unchanged to build/core/tests.

Adaptations are exact, fail-closed replacements, like DOScraft's overlays:
- common.h: Towns hw.h (types plus x86 port I/O) -> n64_compat.h (types
  only); newlib provides NULL and the string functions.
- hdd.h: hw.h -> common.h (only the types are used).
- libc.c: drop the x86-assembly memset/memcpy/memmove/memcmp/strlen;
  itoa_dec, rnd and hash3 stay.
Platform files (video, gfx, sys, sound, save, hdd, bench, crt0, isr, trap.S,
kernel.ld) are not staged: the N64 replaces them.
"""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
TOWNS = ROOT / 'vendor/doscraft/vendor/towns'
TESTS = ROOT / 'vendor/towns-tests'
OUTPUT = ROOT / 'build/core'
EXCLUDED = ('bench.c', 'sys.c', 'video.c', 'gfx.c', 'save.c', 'sound.c', 'hdd.c',
            'crt0.S', 'isr.S', 'trap.S', 'hw.h', 'kernel.ld')

N64_COMPAT = '''/* Generated by tools/stage_core.py: Towns hw.h types without port I/O. */
#ifndef TOWNSCRAFT64_N64_COMPAT_H
#define TOWNSCRAFT64_N64_COMPAT_H
#include <stddef.h>
#include <string.h>
typedef unsigned char u8;
typedef unsigned short u16;
typedef unsigned int u32;
typedef signed char s8;
typedef short s16;
typedef int s32;
/* The Towns core assumes the i386 sizes; o64 with libdragon matches. */
_Static_assert(sizeof(u16) == 2 && sizeof(u32) == 4, "type widths");
_Static_assert(sizeof(int) == 4 && sizeof(long) == 4, "int/long are 32-bit");
_Static_assert(sizeof(void *) == 4 && sizeof(size_t) == 4, "32-bit pointers");
_Static_assert((char)-1 < 0, "char is signed, as on i386");
#endif
'''

LIBC_PROTOTYPES = (
    'void *memset(void *d,int c,unsigned int n);\n',
    'void *memcpy(void *d,const void *s,unsigned int n);\n',
    'void *memmove(void *d,const void *s,unsigned int n);\n',
    'int memcmp(const void *a,const void *b,unsigned int n);\n',
    'int strlen(const char *s);\n',
)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def replace_once(text, before, after, recipe):
    if text.count(before) != 1:
        raise ValueError(f'expected exactly one {before[:40]!r}')
    recipe.append(dict(operation='replace', before_sha256=sha256(before.encode()),
                       before_bytes=len(before.encode()), after=after))
    return text.replace(before, after)


def remove_span(text, start, end, recipe):
    """Remove from the unique `start` up to (not including) the unique `end`."""
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f'span markers not unique: {start[:30]!r} / {end[:30]!r}')
    a, b = text.index(start), text.index(end)
    if a >= b:
        raise ValueError('span markers out of order')
    return replace_once(text, text[a:b], '', recipe)


def adapt(name, text):
    recipe = []
    if '\r\n' in text:
        recipe.append(dict(operation='crlf_to_lf', count=text.count('\r\n')))
        text = text.replace('\r\n', '\n')
    if name == 'common.h':
        text = replace_once(text, '#include "hw.h"', '#include "n64_compat.h"', recipe)
        text = replace_once(text, '#define NULL ((void *)0)\n', '', recipe)
        for line in LIBC_PROTOTYPES:
            text = replace_once(text, line, '', recipe)
    elif name == 'hdd.h':
        text = replace_once(text, '#include "hw.h"', '#include "common.h"', recipe)
    elif name == 'libc.c':
        text = remove_span(text, 'void *memset(void *d,int c,unsigned int n)\n',
                           'char *itoa_dec(int v,char *buf)\n', recipe)
    return text, recipe


def main():
    manifest_bytes = (TOWNS / 'MANIFEST.json').read_bytes()
    manifest = json.loads(manifest_bytes)
    entries = {e['path']: e for e in manifest['files']}
    names = sorted(Path(p).name for p in entries if p.startswith('src/')
                   and Path(p).name not in EXCLUDED)
    staged, records = {}, []
    for name in names:
        data = (TOWNS / 'src' / name).read_bytes()
        entry = entries[f'src/{name}']
        if sha256(data) != entry['sha256'] or len(data) != entry['size']:
            raise RuntimeError(f'Towns snapshot differs from its manifest: {name}')
        text, recipe = adapt(name, data.decode('utf-8'))
        out = text.encode('utf-8')
        staged[name] = out
        records.append(dict(file=f'src/{name}', source_sha256=entry['sha256'],
                            staged_sha256=sha256(out), transformations=recipe))
    staged['n64_compat.h'] = N64_COMPAT.encode('ascii')

    src = OUTPUT / 'src'
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)
    for name, data in staged.items():
        (src / name).write_bytes(data)
    # Towns host tests, staged beside src/ so their "../src/x.c" includes work.
    tests_manifest = json.loads((TESTS / 'MANIFEST.json').read_bytes())
    tests_dir = OUTPUT / 'tests'
    if tests_dir.exists():
        shutil.rmtree(tests_dir)
    tests_dir.mkdir()
    for entry in tests_manifest['files']:
        data = (TESTS / entry['path']).read_bytes()
        if sha256(data) != entry['sha256']:
            raise RuntimeError(f'Towns test differs from its manifest: {entry["path"]}')
        (tests_dir / Path(entry['path']).name).write_bytes(data)
    generator = TOWNS / 'tools/gentables.py'
    if sha256(generator.read_bytes()) != entries['tools/gentables.py']['sha256']:
        raise RuntimeError('gentables.py differs from its manifest')
    subprocess.run([sys.executable, '-I', str(generator), str(src / 'tables.c')], check=True)

    report = dict(towns_commit=manifest['source_commit'],
                  towns_manifest_sha256=sha256(manifest_bytes),
                  excluded=list(EXCLUDED), files=records,
                  generated=[dict(file='src/n64_compat.h', sha256=sha256(staged['n64_compat.h'])),
                             dict(file='src/tables.c', generator='tools/gentables.py',
                                  sha256=sha256((src / 'tables.c').read_bytes()))])
    (OUTPUT / 'stage.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    changed = sum(1 for r in records if r['transformations'])
    print(f'staged {len(records)} Towns files ({changed} adapted) into {src}')


if __name__ == '__main__':
    main()
